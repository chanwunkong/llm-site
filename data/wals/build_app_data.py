# 「我會的語言」可選的 21 種語言；阿拉伯語以標準阿拉伯語（ams）為主，缺的用埃及阿拉伯語（aeg）補
LANGS = [('eng','英語'),('ger','德語'),('spa','西班牙語'),('por','葡萄牙語'),('fre','法語'),('ita','義大利語'),('rus','俄語'),('ben','孟加拉語'),('hin','印地語'),('prs','波斯語'),
         ('ams','阿拉伯語'),('tml','坦米爾語'),('mnd','中文'),('tur','土耳其語'),('jpn','日語'),('kor','韓語'),('vie','越南語'),('ind','印尼語'),('tha','泰語'),('swa','史瓦希里語'),('kgz','吉爾吉斯語')]

stages = json.load(open('../curriculum/wals-stages.json', encoding='utf-8'))['stages']
chapters = sorted({c for s in stages.values() for v in s['domains'].values() for c in v})
feats = {r['feature']: r for r in csv.DictReader(open('grammar-features.csv', encoding='utf-8'))}
# 每章只取主要特徵（例如 90A，不取 90B–G）
main = {}
for fid, r in feats.items():
    ch = int(r['chapter'])
    if ch in chapters and (ch not in main or fid < main[ch]): main[ch] = fid
FEATURES = {}
for ch, fid in sorted(main.items()):
    vals = dict(v.split(':', 1) for v in feats[fid]['values'].split(' | '))
    FEATURES[fid] = {'ch': ch, 'zh': ZH[ch], 'en': feats[fid]['name'],
                     'values': {k: (VZH.get(fid, {}).get(int(k)) or v) for k, v in vals.items()}}
raw = {}
for r in csv.DictReader(open('grammar-values.csv', encoding='utf-8')):
    if r['feature'] in FEATURES: raw.setdefault(r['wals_language'], {})[r['feature']] = r['value_number']
VALUES = {}
for lid, _ in LANGS:
    v = dict(raw.get('aeg', {})) if lid == 'ams' else {}
    v.update(raw.get(lid, {}))
    VALUES[lid] = v

js = ('// 自動產生（data/wals/build_app_data.py），請勿手動修改。\n'
      '// WALS: Dryer, Matthew S. & Haspelmath, Martin (eds.) 2013. The World Atlas of Language Structures Online. https://wals.info (CC BY 4.0)\n'
      f'export const STAGES = {json.dumps(stages, ensure_ascii=False)};\n'
      f'export const FEATURES = {json.dumps(FEATURES, ensure_ascii=False)};\n'
      f'export const LANGS = {json.dumps([{"id": i, "zh": z} for i, z in LANGS], ensure_ascii=False)};\n'
      f'export const VALUES = {json.dumps(VALUES, ensure_ascii=False)};\n')
open('../../site/js/data/wals.js', 'w', encoding='utf-8').write(js)
print('features', len(FEATURES), 'langs', len(VALUES), 'bytes', len(js.encode()))
print('coverage', {l: len(v) for l, v in VALUES.items()})
