# -*- coding: utf-8 -*-
# 產生 docs/curriculum.md：讀取 wals-stages.json 與 site/js/data/wals.js（中文名稱）
import json, re
stages = json.load(open('wals-stages.json', encoding='utf-8'))['stages']
js = open('../../site/js/data/wals.js', encoding='utf-8').read()
FEATURES = json.loads(re.search(r'export const FEATURES = (\{.*?\});\n', js).group(1))
byCh = {f['ch']: (fid, f['zh']) for fid, f in FEATURES.items()}
# 能否用 UD 在句子中判斷：✓ 可、△ 近似或需依存關係、空白 = 只做語言比較（與 site/js/engine/run.js 的 WALS 規則一致）
UD = {81:'△',87:'✓',88:'✓',89:'✓',33:'✓',37:'✓',38:'✓',66:'✓',67:'△',112:'✓',116:'△',85:'✓',86:'△',82:'△',83:'△',65:'✓',68:'△',70:'✓',107:'✓',121:'△',110:'△',111:'△',90:'△',122:'△',53:'△',55:'△'}
IMPL = {'81','87','88','89','33','37','38','66','67','112','116','85'}
CAN = {'A1':'用最常見的字和固定說法，處理打招呼、自我介紹、簡單需求','A2':'處理日常、熟悉的事務，描述自己的背景和周遭','B1':'應付旅行中大多數情況，描述經驗、事件和想法','B2':'和母語者自然地互動，談論各種主題','C1':'流利、有彈性地表達，理解較長和隱含意義的內容','C2':'幾乎能理解所有內容，精確表達細微差異'}
READ = {'A1':'《青蛙與蟾蜍》（Frog and Toad Are Friends）','A2':'《小王子》','B1':'《牧羊少年奇幻之旅》','B2':'《哈利波特：神秘的魔法石》','C1':'各語言的現代文學（見 lang.xlsx「文學」工作表）','C2':'各語言的經典文學（見 lang.xlsx「文學」工作表）'}
out = []
for st, d in stages.items():
    out += [f'\n### {st}\n', f'- **能做什麼（CEFR 能力描述，摘要）**：{CAN[st]}',
            f'- **詞彙量（累計）**：約 {d["vocab"]:,} 字；建議學習時數約 {d["hours"]:,} 小時（英文，依 CEFR-J／Octanove 字表）',
            f'- **分級讀物**：{READ[st]}', '- **文法（WALS）**：\n', '| 領域 | 章 | 內容 | 可計分 | 已實作 |', '|---|---|---|---|---|']
    for dom, chs in d['domains'].items():
        for ch in chs:
            out.append(f'| {dom} | {ch} | {byCh[ch][1]} | {UD.get(ch, "")} | {"✓" if str(ch) in IMPL else ""} |')
body = '\n'.join(out)
doc = f"""# 課綱

> 依使用者整理的 lang.xlsx 規劃，並以 WALS 官方資料核對（核對報告見 [wals-check.md](wals-check.md)）。
> 本文件由 `data/curriculum/build_doc.py` 從 `data/curriculum/wals-stages.json` 產生。

## 一、課綱的結構

每個 CEFR 階段包含四個部分：

| 部分 | 內容 | 在遊戲中的位置 |
|---|---|---|
| 詞彙 | 該階段的累計詞彙量 | 詞彙量（學過、Lv2 以上的字）決定學習者目前在哪個階段 |
| 文法 | 該階段的 WALS 文法章節，分四個領域 | 技能頁：顯示目前階段的規則；和「我會的語言」比較，不同的是難規則 |
| 發音 | 依單字等級的發音重點（見 design.md 第 11 節） | 內層題目的干擾字卡、發音對照表 |
| 讀物 | 該階段適合的分級讀物 | 來源：使用者匯入自己的版本 |

**「可計分」欄**：能不能在句子中用 UD 詞性與特徵自動判斷。✓ 可以；△ 只能近似，或需要詞性標記工具另外提供依存關係；空白 = 整個語言的特性，只放在技能頁的語言比較中。
**「已實作」欄**：目前 demo 已經寫成規則的章節。

## 二、各階段
{body}

## 三、已決定的調整（2026-10-01）

1. 每章的內容一律使用 WALS 的正式名稱（原表有 12 處說明和章節不一致，見 wals-check.md）。
2. B2 詞序的 89（和 A1 重複）改為 90（關係子句），C1 移除 90。
3. 原本沒有分配的 53–56：**55 量詞**放進 A2（依建議）；53 序數詞放 A2、56 連接詞與全稱量詞放 B1、54 分配數詞放 B2（預設，可再調整）。

## 四、注意事項

1. **詞彙量只有英文的數據**：字表來自英文的 CEFR-J（A1–B2）與 Octanove（C1–C2）。其他語言先用同樣的數量當近似值，之後依各語言的字頻表調整。
2. **分級讀物的涵蓋比例沒有核對**：需要實際文本才能計算，而這些書大多仍受著作權保護。讀物只作為建議，由使用者匯入自己的版本。
3. **CEFR 和 WALS 本來沒有對應關係**：CEFR 描述的是溝通能力，WALS 描述的是語言的結構特徵。把 WALS 章節分配到 CEFR 階段，是這個專案自己的教學設計。
"""
open('../../docs/curriculum.md', 'w', encoding='utf-8').write(doc)
print('ok', len(out))
